#!/usr/bin/env bash
# Builds JX808 as a standalone app and/or a VST3 plugin, each in its own folder.
#
#   ./build.sh [standalone|vst3|all]   (default: all)
#
# HISE always exports into Binaries/, so every target is exported there first and then
# synced into build/<Target>/ (the project's relative paths like ../AdditionalSourceCode are
# rewritten one level up). The sync only touches files whose content changed, so each target
# keeps its own incremental build in build/<Target>/Builds/LinuxMakefile/build.
#
# Override the tool locations with HISE_BIN / HISE_PATH. EXPORT_ONLY=1 stops after the export
# (compile elsewhere, e.g. ../build-portable.sh). By default the local HISE of the
# PluginCollection checkout is used (../HISE: binary + source/), if it is there.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOCAL_HISE="$ROOT/../HISE"
if [ -x "$LOCAL_HISE/HISE Standalone" ] && [ -d "$LOCAL_HISE/source" ]; then
	HISE_BIN="${HISE_BIN:-$LOCAL_HISE/HISE Standalone}"
	HISE_PATH="${HISE_PATH:-$(cd "$LOCAL_HISE/source" && pwd)}"
fi
if [ -z "${HISE_BIN:-}" ] || [ -z "${HISE_PATH:-}" ]; then
	echo "HISE not found: put it in ../HISE (binary + source/) or set HISE_BIN and HISE_PATH" >&2
	exit 1
fi
PROJUCER="$HISE_PATH/tools/projucer/Projucer"
# HISE units need about 1.5 GB each: half the cores by default, override with JOBS=...
JOBS="${JOBS:-$(( ($(nproc) + 1) / 2 ))}"

# The version must be MAJOR.MINOR.PATCH (set only in project_info.xml)
VERSION="$(sed -n 's/.*<Version value="\([^"]*\)".*/\1/p' "$ROOT/project_info.xml")"
if ! [[ "$VERSION" =~ ^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$ ]]; then
	echo "project_info.xml: Version '$VERSION' is not MAJOR.MINOR.PATCH" >&2
	exit 1
fi
echo "==> JX808 $VERSION"

build_target() {
	local name="$1"; shift
	local dest="$ROOT/build/$name"

	echo "==> [$name] exporting"
	"$HISE_BIN" export "$ROOT/XmlPresetBackups/JX808.xml" -h:"$HISE_PATH" -nolto "$@"

	echo "==> [$name] syncing Binaries/ -> build/$name/"
	mkdir -p "$dest"
	# -c without -t: unchanged files keep their old mtime, so make stays incremental
	rsync -r -c -p --delete --exclude /Builds/LinuxMakefile/build "$ROOT/Binaries/" "$dest/"
	# build/<Target> is one level deeper than Binaries/: ../X -> ../../X
	sed -i 's#\.\./#../../#g' "$dest/AutogeneratedProject.jucer"

	(cd "$dest" && "$PROJUCER" --resave AutogeneratedProject.jucer)

	if [ "${EXPORT_ONLY:-0}" = 1 ]; then
		echo "==> [$name] exported only (EXPORT_ONLY=1)"
		return
	fi

	echo "==> [$name] compiling"
	# JUCE_USE_CURL=0: the node doesn't use networking, and libcurl-devel isn't required.
	# Without the JACK headers the standalone uses ALSA only.
	local cppflags="-DJUCE_USE_CURL=0"
	pkg-config --exists jack || cppflags="$cppflags -DJUCE_JACK=0"
	make -C "$dest/Builds/LinuxMakefile" CONFIG=Release AR=gcc-ar CPPFLAGS="$cppflags" -j"$JOBS"
}

target="${1:-all}"

case "$target" in
	standalone) build_target Standalone -t:standalone ;;
	vst3)       build_target VST3 -t:instrument -p:VST3 ;;
	all)        build_target Standalone -t:standalone
	            build_target VST3 -t:instrument -p:VST3 ;;
	*)          echo "usage: $0 [standalone|vst3|all]" >&2; exit 1 ;;
esac

echo "==> outputs"
find "$ROOT"/build/*/Builds/LinuxMakefile/build -maxdepth 1 \( -name JX808 -o -name '*.vst3' \) 2>/dev/null
